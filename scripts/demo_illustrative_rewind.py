#!/usr/bin/env python3
"""Create a model-generated illustrative research and rewind replay."""

from __future__ import annotations

import argparse
import json
import uuid
from pathlib import Path
from typing import Any

from dotenv import load_dotenv
from langchain.chat_models import init_chat_model
from langchain_core.messages import HumanMessage, SystemMessage

from demo_forced_rewind import ROOT, copy_context
from open_deep_research.configuration import Configuration
from open_deep_research.epistemic_graph import EpistemicGraph
from open_deep_research.utils import get_api_key_for_model, get_base_url_for_model
from open_deep_research.world_model import WorldModel
from open_deep_research.world_model_logger import WorldModelRun
from open_deep_research.world_model_monitor import monitor
from open_deep_research.world_model_rollback import apply_repair, reduced_repair
from open_deep_research.world_model_scoring import compute_belief, take_snapshot
from visualize_replay import make_replay

NOTICE = (
    "Illustrative example based on a recorded graph snapshot. Research notes are "
    "generated by the model, not actual search results; the commitment is manually introduced."
)
SCENARIO_PROMPT = """Create a coherent illustrative research sequence based on the provided topic.
Return only one JSON object with these non-empty string keys:
claim, hypothesis, first_query, first_finding, second_query, second_finding.
The claim must be one specific, testable working conclusion.
The first finding must support that conclusion. The second finding must directly
contradict it for the same scenario, not merely describe a different scenario.
Make the findings sound like concise research notes on rooftop solar.
Use a hypothetical household or contract, not assertions about real policies.
Do not invent or name real publications, websites, people, or URLs.
The later finding should introduce an identifiable changed assumption or error.
Keep each value to at most two short sentences.
"""
FIELDS = ("claim", "hypothesis", "first_query", "first_finding", "second_query", "second_finding")


def generate_scenario(client: Any, context: str) -> dict[str, str]:
    """Generate an illustrative research sequence, without inventing citations."""
    response = client.invoke([
        SystemMessage(content=SCENARIO_PROMPT),
        HumanMessage(content=f"Topic context:\n{context[:4000]}"),
    ])
    content = response if isinstance(response, str) else response.content
    if not isinstance(content, str):
        raise ValueError("The scenario model returned non-text content.")
    start, end = content.find("{"), content.rfind("}")
    if start < 0 or end < start:
        raise ValueError("The scenario model did not return a JSON object.")
    data = json.loads(content[start:end + 1])
    if not isinstance(data, dict) or any(
        not isinstance(data.get(field), str) or not data[field].strip() for field in FIELDS
    ):
        raise ValueError("The scenario model omitted a required text field.")
    return {field: data[field].strip() for field in FIELDS}


def demonstrate(source: Path, output: Path, model_name: str, client: Any = None) -> dict[str, Any]:
    """Generate scenario notes and run the actual world-model and rollback logic."""
    output.mkdir(parents=True, exist_ok=False)
    run_id = f"example-{uuid.uuid4()}"
    config = {"configurable": {
        "thread_id": run_id, "enable_world_model": True, "world_model_model": model_name,
        "wm_enforce_decision": False, "wm_enable_rollback": True, "wm_enforce_rollback": True,
    }}
    settings = Configuration.from_runnable_config(config)
    graph = EpistemicGraph(run_id, str(output))
    logger = WorldModelRun(run_id, str(output), config, question=NOTICE)
    try:
        original_claim_id = copy_context(source, graph, question=NOTICE)
        original_claim = graph.get_node(original_claim_id)
        if not original_claim:
            raise RuntimeError("The copied claim is missing.")
        if client is None:
            client = init_chat_model(
                model_name, api_key=get_api_key_for_model(model_name, config),
                base_url=get_base_url_for_model(model_name, config), max_tokens=1800,
            )
        print("Generating an illustrative research sequence with Qwen...", flush=True)
        scenario = generate_scenario(client, str(original_claim.get("text", "")))
        meta = {"origin": "model-generated research note"}
        claim = graph.add_claim(scenario["claim"], metadata=meta)
        hypothesis = graph.add_hypothesis(scenario["hypothesis"], metadata=meta)
        first_source = graph.add_source(
            "Research note: " + scenario["first_query"], metadata={**meta, "reliability": 0.7},
        )
        first_evidence = graph.add_evidence(
            scenario["first_finding"], metadata={**meta, "iteration": 1},
            sources=[first_source] if first_source else None,
        )
        if not all((claim, hypothesis, first_source, first_evidence)):
            raise RuntimeError("Could not record the initial scenario.")
        graph.derived_from(claim, original_claim_id)
        graph.supports(first_evidence, claim, weight=0.8)
        graph.depends_on(hypothesis, claim)

        model = WorldModel(config, prediction_client=client)
        print("Predicting the commitment with Qwen...", flush=True)
        prediction = model.predict(graph, {"action_id": "example-commit", "target_node_ids": [claim, hypothesis]})
        logger.prediction(prediction)
        if prediction.parse_error:
            raise ValueError("The world-model response was not valid JSON; no outcome was fabricated.")
        commitment = graph.add_commitment(
            "Commit to the working research conclusion", target=claim,
            metadata={"origin": "interactive example", "model_decision": prediction.decision},
        )
        if not commitment:
            raise RuntimeError("Could not record the commitment.")
        model.register_active_commitment(commitment, claim, hypothesis, prediction.resolved_theta, 1)
        before = compute_belief(take_snapshot(graph), claim, settings)
        model.active_commitments[commitment]["beta_at_commit"] = before
        second_source = graph.add_source(
            "Research note: " + scenario["second_query"], metadata={**meta, "reliability": 1.0},
        )
        second_evidence = graph.add_evidence(
            scenario["second_finding"], metadata={**meta, "iteration": 2},
            sources=[second_source] if second_source else None,
        )
        if not second_source or not second_evidence:
            raise RuntimeError("Could not record the later research note.")
        graph.contradicts(second_evidence, claim, weight=1.0, iteration=2)
        fired = monitor(graph, model.active_commitments, settings)
        logger.monitor_check({"step": 2, "n_active": 1, "n_fired": len(fired), "origin": "illustrative example"})
        if not fired:
            raise RuntimeError("The monitor did not fire for the generated evidence; no rollback was fabricated.")
        item = fired[0]
        repair = reduced_repair(graph, item, settings)
        payload = {
            "step": 2, "origin": "illustrative example", "commitment_id": commitment, "claim_id": claim,
            "beta_before": before, "beta_after": item["detail"]["beta_now"],
            "offending_evidence_ids": item["detail"]["offending_evidence_ids"],
            "contested_claims": repair.contested_claims, "retract_nodes": repair.retract_nodes,
            "retract_edges": repair.retract_edges, "regenerate_nodes": repair.regenerate_nodes,
            "preserved_nodes": repair.preserved_nodes, "reopen_claims": repair.reopen_claims,
            "enforced": True,
        }
        logger.trigger_fired(payload)
        apply_repair(graph, repair, settings)
        model.unregister_active_commitment(commitment)
        logger.rollback(payload)
        logger.finish()
        graph.finish({"origin": "illustrative example"})
        replay = make_replay(
            Path(graph.graph_path), Path(logger.log_path), output / "replay.html",
            notice=NOTICE, initial_event="prediction",
        )
        return {
            "replay": replay, "graph": Path(graph.graph_path), "world_log": Path(logger.log_path),
            "scenario": scenario, "decision": prediction.decision,
            "beta_before": before, "beta_after": item["detail"]["beta_now"],
        }
    except Exception:
        logger.finish()
        graph.finish({"origin": "illustrative example", "status": "failed"})
        raise


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("graph", type=Path)
    parser.add_argument("--model", default="openai:qwen/qwen3.5-27b")
    parser.add_argument("--output-dir", type=Path)
    args = parser.parse_args()
    load_dotenv(ROOT / ".env")
    output = args.output_dir or Path("reports") / f"research-example-{uuid.uuid4().hex[:8]}"
    result = demonstrate(args.graph, output, args.model)
    print(f"Replay: {result['replay']}")
    print(f"World-model log: {result['world_log']}")
    print(f"Decision: {result['decision']}; belief: {result['beta_before']:.3f} -> {result['beta_after']:.3f}")


if __name__ == "__main__":
    main()
